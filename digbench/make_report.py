"""Build digbench/RESULTS.md from results/*.json (only measured runs; nothing typed by hand)."""
import json
from pathlib import Path

R = Path(__file__).resolve().parent / "results"
rows = []
for p in sorted(R.glob("collapse-*.json")):
    d = json.loads(p.read_text())
    pr = d.get("params", {})
    cfg = d["solver"]
    if cfg.startswith("mls-mpm"):
        bits = [pr.get("rheology", "const"), pr.get("yield_fit", "klar3d")]
        if pr.get("side_W"):
            bits.append(f"sidewall W={pr['side_W']} mu={pr['side_mu']}")
        if pr.get("wall_mu"):
            bits.append(f"backwall mu={pr['wall_mu']}")
        if pr.get("floor") != "sticky":
            bits.append(f"floor {pr.get('floor')} mu={pr.get('floor_mu')}")
        if pr.get("dilatancy_deg"):
            bits.append(f"dilatancy psi0={pr['dilatancy_deg']} deg (ev_max {pr.get('dilatancy_evmax')})")
        bits.append(f"phi={pr.get('phi_deg')}")
        bits.append(f"E={pr.get('E'):.0e}")
        cfg = f"MPM dx={pr['dx']*1000:g} mm; " + ", ".join(bits)
    else:
        cfg = f"LiveDirt heightfield (cell {pr['cell']*1000:g} mm, repose {pr['reposeDeg']} deg)"
    cs = d["cases"]
    wall = sum(c.get("wall_s", 0) for c in cs)
    rows.append((d["summary"]["runout_mae_rel"], d["summary"]["height_mae_rel"], d["tag"], cfg, d.get("device", "cpu (node)"), wall, cs))

rows.sort(key=lambda r: r[0] + r[1])
out = ["# DigBench results", "",
       "Generated by `digbench/make_report.py` from `digbench/results/*.json`. Every number comes from a run.", "",
       "## Task 1: quasi-2D granular column collapse", "",
       "Reference: Sarlin et al. 2021, Phys. Rev. E 104, 064904 (arXiv:2112.11458), Series A power-law fits for glass beads "
       "(d = 5 mm, repose 23.5 +/- 1.2 deg). Seven aspect ratios a = 0.5 to 12. Error = (sim - fit) / fit for normalized runout "
       "dL/L0 and final height Hf/L0. The fits summarize scattered data; their scatter is not modeled here.", "",
       "| rank | config | runout MAE | height MAE | total sim wall time | device | tag |", "|---|---|---|---|---|---|---|"]
for i, (ro, he, tag, cfg, dev, wall, cs) in enumerate(rows, 1):
    out.append(f"| {i} | {cfg} | {ro:.1%} | {he:.1%} | {wall:.1f} s | {dev} | `{tag}` |")
out += ["", "### Per-case errors (runout / height)", "", "| tag | " + " | ".join(f"a={c['a']:g}" for c in rows[0][6]) + " |",
        "|---|" + "---|" * len(rows[0][6])]
for ro, he, tag, cfg, dev, wall, cs in rows:
    out.append(f"| `{tag}` | " + " | ".join(f"{c['runout_relerr']:+.0%} / {c['height_relerr']:+.0%}" for c in cs) + " |")
(R.parent / "RESULTS.md").write_text("\n".join(out) + "\n")
print("\n".join(out[:12 + len(rows)]))


